import { describe, it, expect } from 'vitest';
import { serializeHookOutput } from '../../src/utils/hook-output.js';

describe('serializeHookOutput', () => {
  it('moves additionalContext into the documented hookSpecificOutput shape (a top-level key is ignored by Claude Code)', () => {
    const j = JSON.parse(serializeHookOutput({ additionalContext: 'recalled thing', systemMessage: 'johnny · t1' }));
    expect(j.additionalContext).toBeUndefined();
    expect(j.hookSpecificOutput).toEqual({ hookEventName: 'UserPromptSubmit', additionalContext: 'recalled thing' });
    expect(j.systemMessage).toBe('johnny · t1');
  });
  it('legacy hints are dropped unless opted in; knowledge priming always flows and is merged first', () => {
    const both = { additionalContext: 'legacy offer', knowledgeContext: 'compiled digest' };
    const off = JSON.parse(serializeHookOutput(both, 'UserPromptSubmit', { legacyHints: false }));
    expect(off.hookSpecificOutput.additionalContext).toBe('compiled digest');
    const on = JSON.parse(serializeHookOutput(both, 'UserPromptSubmit', { legacyHints: true }));
    expect(on.hookSpecificOutput.additionalContext).toBe('compiled digest\n\n---\n\nlegacy offer');
    expect(JSON.parse(serializeHookOutput({ additionalContext: 'only legacy' }, 'UserPromptSubmit', { legacyHints: false })).hookSpecificOutput).toBeUndefined();
    expect(JSON.parse(serializeHookOutput(both)).knowledgeContext).toBeUndefined(); // internal key never printed
  });

  it('omits hookSpecificOutput when there is no context, and keeps decision/reason', () => {
    expect(JSON.parse(serializeHookOutput({ systemMessage: 'x' }))).toEqual({ systemMessage: 'x' });
    expect(JSON.parse(serializeHookOutput({ additionalContext: '   ' })).hookSpecificOutput).toBeUndefined();
    expect(JSON.parse(serializeHookOutput({ decision: 'block', reason: 'r' }))).toEqual({ decision: 'block', reason: 'r' });
  });
  it('honours the event name', () => {
    expect(JSON.parse(serializeHookOutput({ additionalContext: 'c' }, 'PreToolUse')).hookSpecificOutput.hookEventName).toBe('PreToolUse');
  });
});

import { isSystemNotificationPrompt } from '../../src/cli/evaluate.js';

describe('isSystemNotificationPrompt', () => {
  it('recognises machine-generated prompts that carry no user intent', () => {
    expect(isSystemNotificationPrompt('<task-notification>\n<task-id>abc</task-id>')).toBe(true);
    expect(isSystemNotificationPrompt('  <system-reminder>hi</system-reminder>')).toBe(true);
    expect(isSystemNotificationPrompt('[SYSTEM NOTIFICATION - NOT USER INPUT] background task done')).toBe(true);
    expect(isSystemNotificationPrompt('<local-command-caveat>Caveat: The messages below were generated by the user')).toBe(true);
    expect(isSystemNotificationPrompt('This session is being continued from a previous conversation that ran out of context.')).toBe(true);
  });
  it('does not swallow real user prompts that merely mention notifications', () => {
    expect(isSystemNotificationPrompt('how do task-notification prompts get classified?')).toBe(false);
    expect(isSystemNotificationPrompt('please fix the build')).toBe(false);
    expect(isSystemNotificationPrompt('')).toBe(false);
  });
});
