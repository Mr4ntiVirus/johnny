// Scheduler wiring for the synthesis heartbeat: a plain LaunchAgent running a
// wrapper every 3h (+ at login). No window, no human: the wrapper does a free
// precheck (`johnny synth status --exit-code`, no network, no model calls) and
// exits immediately unless work is pending; otherwise it runs the governed
// synthesis pass and emails an after-action report. launchd shows it in the
// Johnny Control panel automatically (that panel lists every launchd job).
//
// Installing never starts it: `install` only writes files; `arm` loads the
// LaunchAgent. (Supervised backfill first, arm last.)

import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { execFileSync } from 'node:child_process';
import { PATHS } from '../store/paths.js';
import { readJsonFile, writeJsonFile } from '../utils/jsonl.js';

export const LABEL = 'com.positronik.johnny.synthesis';
export const INTERVAL_SECONDS = 3 * 60 * 60;

const home = () => os.homedir();
export const scriptPath = () => path.join(home(), '.johnny', 'synth-heartbeat.sh');
export const plistPath = () => path.join(home(), 'Library', 'LaunchAgents', `${LABEL}.plist`);

export function heartbeatScript(): string {
  return `#!/bin/bash
# Johnny memory-synthesis heartbeat — generated by \`johnny synth install\`. Do not hand-edit.
# Headless: runs under launchd every ${INTERVAL_SECONDS / 3600}h. Free precheck first; model calls only when work is pending.

NVM_DIR="$HOME/.nvm"
if [ -f "$NVM_DIR/alias/default" ]; then
  V=$(cat "$NVM_DIR/alias/default" | tr -d '[:space:]')
  for _ in 1 2 3; do [ -f "$NVM_DIR/alias/$V" ] && V=$(cat "$NVM_DIR/alias/$V" | tr -d '[:space:]'); done
  [ -x "$NVM_DIR/versions/node/$V/bin/node" ] && export PATH="$NVM_DIR/versions/node/$V/bin:$PATH"
fi
if ! command -v node >/dev/null 2>&1; then
  F=$(ls -d "$NVM_DIR/versions/node"/*/bin/node 2>/dev/null | sort -V | tail -1)
  [ -n "$F" ] && export PATH="$(dirname "$F"):$PATH"
fi
export PATH="$PATH:/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin"
LOG="$HOME/.johnny/synth.log"

# 1. zero-cost precheck: exit 75 = nothing pending
johnny synth status --exit-code >/dev/null 2>&1
[ $? -eq 75 ] && exit 0

# 2. claude needs the network; offline => skip quietly, next heartbeat retries
/usr/bin/curl -s -m 8 -o /dev/null https://api.anthropic.com || exit 0

# 3. one governed pass (the job itself enforces caps, time box and rate-limit backoff)
{ echo "=== $(date '+%Y-%m-%d %H:%M:%S') ==="; johnny synth run; echo; } >> "$LOG" 2>&1
`;
}

export function plistXml(): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>${LABEL}</string>
    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>${scriptPath()}</string>
    </array>
    <key>StartInterval</key>
    <integer>${INTERVAL_SECONDS}</integer>
    <key>RunAtLoad</key>
    <true/>
    <key>ProcessType</key>
    <string>Background</string>
    <key>LowPriorityIO</key>
    <true/>
    <key>Nice</key>
    <integer>10</integer>
    <key>StandardOutPath</key>
    <string>${path.join(home(), '.johnny', 'synth-launchd.log')}</string>
    <key>StandardErrorPath</key>
    <string>${path.join(home(), '.johnny', 'synth-launchd.log')}</string>
</dict>
</plist>
`;
}

export function installHeartbeatFiles(): { script: string; plist: string } {
  fs.mkdirSync(path.dirname(scriptPath()), { recursive: true });
  fs.writeFileSync(scriptPath(), heartbeatScript(), { mode: 0o755 });
  fs.mkdirSync(path.dirname(plistPath()), { recursive: true });
  fs.writeFileSync(plistPath(), plistXml());
  return { script: scriptPath(), plist: plistPath() };
}

const uid = () => (process.getuid ? process.getuid() : 501);

export function isArmed(): boolean {
  try { execFileSync('launchctl', ['print', `gui/${uid()}/${LABEL}`], { stdio: 'ignore' }); return true; }
  catch { return false; }
}

export function arm(): void {
  if (!fs.existsSync(plistPath())) installHeartbeatFiles();
  if (isArmed()) return;
  execFileSync('launchctl', ['bootstrap', `gui/${uid()}`, plistPath()]);
}

/** Record the user's choice in ~/.johnny/config.json (knowledge.autoSynth). */
export async function setAutoSynth(value: boolean): Promise<void> {
  const saved = (await readJsonFile<Record<string, unknown>>(PATHS.config)) ?? {};
  const knowledge = { ...((saved.knowledge as Record<string, unknown>) ?? {}), autoSynth: value };
  await writeJsonFile(PATHS.config, { ...saved, knowledge });
}

/** Idempotent: arm the heartbeat if it is not loaded. Never throws (used from the daemon). */
export function ensureArmed(): boolean {
  try { arm(); return isArmed(); } catch { return false; }
}

/** Disarm and delete the script and plist (used by uninstall). */
export function removeHeartbeat(): void {
  try { disarm(); } catch { /* not loaded */ }
  for (const f of [plistPath(), scriptPath()]) { try { fs.unlinkSync(f); } catch { /* absent */ } }
}

export function disarm(): void {
  if (!isArmed()) return;
  execFileSync('launchctl', ['bootout', `gui/${uid()}/${LABEL}`]);
}
